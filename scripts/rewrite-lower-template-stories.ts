function isTemplateStory(text: string): boolean {
  return TEMPLATE_MARKERS.some((marker) => text.includes(marker));
}

function rewriteStory(char: string, index: number): string {
  if (EXACT_STORIES[char]) return EXACT_STORIES[char];
  const group = GROUPS.find((item) => item.chars.includes(char));
  if (group) return group.story(char);
  return FALLBACKS[index % FALLBACKS.length](char);
}

function main() {
  if (!fs.existsSync(DATA_PATH)) {
    throw new Error(`找不到数据文件：${DATA_PATH}`);
  }
  if (!fs.existsSync(BACKUP_PATH)) {
    fs.copyFileSync(DATA_PATH, BACKUP_PATH);
  }

  const ds = JSON.parse(fs.readFileSync(DATA_PATH, 'utf8')) as Dataset;
  let rewritten = 0;
  const rewrittenChars: string[] = [];

  ds.characters.forEach((item, index) => {
    if (item.volume !== 'lower') return;
    if (!isTemplateStory(item.story?.text || '')) return;

    const text = rewriteStory(item.char, index);
    item.story = {
      text,
      annotated: annotateText(text),
    };
    rewritten++;
    rewrittenChars.push(item.char);
  });

  ds.generatedAt = new Date().toISOString();
  fs.writeFileSync(DATA_PATH, JSON.stringify(ds, null, 2), 'utf8');

  console.log(`重写下册模板故事：${rewritten}`);
  console.log(`涉及字符：${rewrittenChars.join('')}`);
  console.log(`备份文件：${path.relative(ROOT, BACKUP_PATH)}`);
}

main();
