// ============================================================
// 工具：去重、过滤非汉字
// ============================================================
function dedupHanzi(arr: string[]): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const raw of arr) {
    if (!raw) continue;
    for (const ch of raw) {
      if (/[\u4e00-\u9fff]/.test(ch) && !seen.has(ch)) {
        seen.add(ch);
        out.push(ch);
      }
    }
  }
  return out;
}

export const sections: WordListSection[] = [
  {
    volume: 'upper',
    label: '一年级上册',
    chars: dedupHanzi(upperGradeChars),
  },
  {
    volume: 'lower',
    label: '一年级下册',
    chars: dedupHanzi(lowerGradeChars),
  },
];

// 全部字（"上册→下册"顺序、跨册去重）
export const allChars: string[] = (() => {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const s of sections) {
    for (const c of s.chars) {
      if (!seen.has(c)) {
        seen.add(c);
        out.push(c);
      }
    }
  }
  return out;
})();

// 标记字属于哪个册
export function getVolumeOf(char: string): 'upper' | 'lower' | 'unknown' {
  for (const s of sections) {
    if (s.chars.includes(char)) return s.volume;
  }
  return 'unknown';
}

